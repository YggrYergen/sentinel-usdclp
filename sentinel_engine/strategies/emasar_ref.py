    highs = [b["high"] for b in bars]
    lows = [b["low"] for b in bars]
    closes = [b["close"] for b in bars]

    ema8 = ema_series(closes, ema_fast)
    ema20 = ema_series(closes, ema_slow)
    ema5 = ema_series(closes, ema_pull) if strategy_mode == 2 else [None] * n
    _sar_val, sar_trend = sar_series(highs, lows, sar_step, sar_max)
    ao = ao_series(highs, lows)
    ac = ac_series(highs, lows)
