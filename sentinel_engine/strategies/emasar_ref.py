# ---------- helpers puros ----------
def _sma_maybe(vals, n):
    """SMA de ventana n; None si algun elemento de la ventana es None o falta historia."""
    out = [None] * len(vals)
    for i in range(len(vals)):
        if i < n - 1:
            continue
        ventana = vals[i - n + 1:i + 1]
        if any(v is None for v in ventana):
            continue
        out[i] = sum(ventana) / n
    return out


# ---------- indicadores ----------
def ema_series(closes, period):
    """EMA estandar: semilla SMA(period) en la primera ventana completa, recursion despues.
    None mientras no hay historia suficiente (paridad con iMA modo EMA de MT5)."""
    n = len(closes)
    out = [None] * n
    if n < period:
        return out
    k = 2.0 / (period + 1)
    seed = sum(closes[0:period]) / period
    out[period - 1] = seed
    for i in range(period, n):
        out[i] = closes[i] * k + out[i - 1] * (1 - k)
    return out


def sar_series(highs, lows, step, max_step):
    """Parabolic SAR estandar (recursion Wilder), identica a stac_ref.sar_series.
    trend[i]: +1 = SAR bajo el precio (alcista), -1 = SAR sobre el precio (bajista)."""
    n = len(highs)
    if n == 0:
        return [], []
    sar = [None] * n
    trend = [0] * n
    up = True if n < 2 else highs[1] >= highs[0]
    ep = highs[0] if up else lows[0]
    af = step
    sar[0] = lows[0] if up else highs[0]
    trend[0] = +1 if up else -1
    for i in range(1, n):
        cur = sar[i - 1] + af * (ep - sar[i - 1])
        if up:
            techo = min(lows[i - 1], lows[i - 2]) if i >= 2 else lows[i - 1]
            cur = min(cur, techo)
            if lows[i] < cur:
                up = False
                cur = ep
                ep = lows[i]
                af = step
            elif highs[i] > ep:
                ep = highs[i]
                af = min(af + step, max_step)
        else:
            piso = max(highs[i - 1], highs[i - 2]) if i >= 2 else highs[i - 1]
            cur = max(cur, piso)
            if highs[i] > cur:
                up = True
                cur = ep
                ep = highs[i]
                af = step
            elif lows[i] < ep:
                ep = lows[i]
                af = min(af + step, max_step)
        sar[i] = cur
        trend[i] = +1 if up else -1
    return sar, trend


def ao_series(highs, lows):
    """AO = SMA(mediana,5) - SMA(mediana,34), mediana=(H+L)/2 (spec S2)."""
    median = [(highs[i] + lows[i]) / 2.0 for i in range(len(highs))]
    sma5 = _sma_maybe(median, 5)
    sma34 = _sma_maybe(median, 34)
    return [None if (sma5[i] is None or sma34[i] is None) else sma5[i] - sma34[i]
            for i in range(len(median))]


def ac_series(highs, lows):
    """AC = AO - SMA(AO,5) (spec S2)."""
    ao = ao_series(highs, lows)
    ao_sma5 = _sma_maybe(ao, 5)
    return [None if (ao[i] is None or ao_sma5[i] is None) else ao[i] - ao_sma5[i]
            for i in range(len(ao))]


def momentum_series(closes, period):
    """Momentum estandar MT5: 100 * close[i] / close[i-period]. None sin historia suficiente."""
    n = len(closes)
    out = [None] * n
    for i in range(period, n):
        out[i] = 100.0 * closes[i] / closes[i - period]
    return out


# ---------- ConfirmMode (S2) ----------
def oscilador_favorable(osc, i, mode, direccion):
    """osc[i]=valor en indice [1] del spec, osc[i-1]=[2], osc[i-2]=[3]. direccion:
    +1 = favorable a LONG, -1 = favorable a SHORT. mode: 1=creciente, 2=acelerando.
    Requiere historia suficiente (None -> no favorable)."""
    if i < 1 or osc[i] is None or osc[i - 1] is None:
        return False
    if mode == 1:
        return (osc[i] > osc[i - 1]) if direccion == +1 else (osc[i] < osc[i - 1])
    if mode == 2:
        if i < 2 or osc[i - 2] is None:
            return False
        d1 = osc[i] - osc[i - 1]
        d2 = osc[i - 1] - osc[i - 2]
        return (d1 > d2) if direccion == +1 else (d1 < d2)
    raise ValueError(f"ConfirmMode invalido: {mode}")


def g5_confirmacion(ao, ac, mom, i, mode, direccion, *, confirm_count=2, ac_mag_threshold=0.0):
    """G5: >=confirm_count de 3 osciladores {AO, Momentum, AC} favorables segun ConfirmMode
    (spec S1/S2 Fase 0; ConfirmCount y AC_MagThreshold: spec Fase 1 S1). confirm_count=2
    (Fase 0, default) o 3 (exige los 3). ac_mag_threshold>0 anade a G5 la exigencia de
    magnitud minima de aceleracion: |AC[i]-AC[i-1]| > ac_mag_threshold."""
    votos = sum([
        oscilador_favorable(ao, i, mode, direccion),
        oscilador_favorable(mom, i, mode, direccion),
        oscilador_favorable(ac, i, mode, direccion),
    ])
    if votos < confirm_count:
        return False
    if ac_mag_threshold > 0.0:
        if i < 1 or ac[i] is None or ac[i - 1] is None:
            return False
        if abs(ac[i] - ac[i - 1]) <= ac_mag_threshold:
            return False
    return True


# ---------- Engulfing (S4) ----------
def bearish_engulfing(o1, c1, o2, c2):
    """Cierre de LONG: [1] bajista, [2] alcista, cuerpo de [1] engulle al de [2]."""
    return (c1 < o1) and (c2 > o2) and (o1 >= c2) and (c1 <= o2)


def bullish_engulfing(o1, c1, o2, c2):
    """Cierre de SHORT (espejo): [1] alcista, [2] bajista, cuerpo de [1] engulle al de [2]."""
    return (c1 > o1) and (c2 < o2) and (o1 <= c2) and (c1 >= o2)


# ---------- Gate compuesto de entrada (S1) ----------
def gate_long(bars, ema8, ema20, ema5, sar_trend, ao, ac, mom, i, *, confirm_mode, use_ema5,
              confirm_count=2, ac_mag_threshold=0.0, skip_g3=False, require_ema_order=True):
    """Evalua G1..G5 para LONG en indice i (>=2 de historia). use_ema5: True para V2 (G3
    usa EMA5), False para V1 (G3 usa EMA8). Devuelve (True/False, detalle dict de gates).
    confirm_count/ac_mag_threshold: extensiones Fase 1 (defaults preservan Fase 0). skip_g3
    (EntryTiming=1): omite G3 (el toque intrabar lo reemplaza en el llamador, spec Fase1 S1).
    require_ema_order (correccion trader 2026-07-09): True (default, Fase 0) exige G1
    (EMA8>EMA20). False lo omite del AND: basta con que ambas EMAs vayan en la MISMA
    orientacion (G2) sin importar cual esta sobre cual -> mas entradas."""
    if i < 2:
        return False, {}
    e8, e8p = ema8[i], ema8[i - 1]
    e20, e20p = ema20[i], ema20[i - 1]
    if None in (e8, e8p, e20, e20p) or sar_trend[i] is None:
        return False, {}
    g1 = e8 > e20
    slope8 = e8 - e8p
    slope20 = e20 - e20p
    # G2: cruzadas (signos opuestos de pendiente) -> no opera en ningun lado.
    cruzadas = (slope8 > 0 and slope20 < 0) or (slope8 < 0 and slope20 > 0)
    g2 = (slope8 > 0 and slope20 > 0) and not cruzadas
    ema_pull = ema5[i] if use_ema5 else ema8[i]
    if ema_pull is None:
        return False, {}
    if skip_g3:
        g3 = True
    else:
        bar1 = bars[i]
        g3 = (bar1["low"] < ema_pull) and (bar1["close"] > bar1["open"])
    g4 = sar_trend[i] == +1
    g5 = g5_confirmacion(ao, ac, mom, i, confirm_mode, +1,
                          confirm_count=confirm_count, ac_mag_threshold=ac_mag_threshold)
    detalle = dict(g1=g1, g2=g2, g3=g3, g4=g4, g5=g5)
    g1_efectivo = g1 if require_ema_order else True
    return (g1_efectivo and g2 and g3 and g4 and g5), detalle


def gate_short(bars, ema8, ema20, ema5, sar_trend, ao, ac, mom, i, *, confirm_mode, use_ema5,
               confirm_count=2, ac_mag_threshold=0.0, skip_g3=False, require_ema_order=True):
    """Espejo exacto de gate_long (S1.1). require_ema_order: ver gate_long."""
    if i < 2:
        return False, {}
    e8, e8p = ema8[i], ema8[i - 1]
    e20, e20p = ema20[i], ema20[i - 1]
    if None in (e8, e8p, e20, e20p) or sar_trend[i] is None:
        return False, {}
    g1 = e8 < e20
    slope8 = e8 - e8p
    slope20 = e20 - e20p
    cruzadas = (slope8 > 0 and slope20 < 0) or (slope8 < 0 and slope20 > 0)
    g2 = (slope8 < 0 and slope20 < 0) and not cruzadas
    ema_pull = ema5[i] if use_ema5 else ema8[i]
    if ema_pull is None:
        return False, {}
    if skip_g3:
        g3 = True
    else:
        bar1 = bars[i]
        g3 = (bar1["high"] > ema_pull) and (bar1["close"] < bar1["open"])
    g4 = sar_trend[i] == -1
    g5 = g5_confirmacion(ao, ac, mom, i, confirm_mode, -1,
                          confirm_count=confirm_count, ac_mag_threshold=ac_mag_threshold)
    detalle = dict(g1=g1, g2=g2, g3=g3, g4=g4, g5=g5)
    g1_efectivo = g1 if require_ema_order else True
    return (g1_efectivo and g2 and g3 and g4 and g5), detalle


